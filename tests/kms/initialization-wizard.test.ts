import { beforeEach, expect, it, vi } from 'vitest';
import { flushPromises, mount } from '@vue/test-utils';
import ElementPlus from 'element-plus';
import Wizard from '@/views/kms/init/index.vue';
import * as api from '@/api/kms/initialization';
import type { InitializationPlan } from '@/api/kms/initialization';
vi.mock('vue-router', () => ({ useRouter: () => ({ replace: vi.fn() }) }));
vi.mock('@/api/kms/initialization', () => ({ getKmsInitialization: vi.fn(), getKmsInitializationPlan: vi.fn(), recheckKmsInitialization: vi.fn(), confirmKmsInitializationStep: vi.fn(), testKmsInitialization: vi.fn(), completeKmsInitialization: vi.fn() }));
let plan: InitializationPlan;
const create = () => mount(Wizard, { global: { plugins: [ElementPlus], stubs: { Agreement: { template: '<p>公共用户协议</p>' } } } });
beforeEach(() => {
  vi.clearAllMocks();
  plan = { status: { revision: 1, step: 1, locked: false, canInitialize: true, completedAt: 0 }, checks: [], revisions: { device: 'd1' }, summary: { agreementVersion: '2026-10-12' }, boundAccounts: [], verificationId: '', expiresAt: 0 };
  vi.mocked(api.getKmsInitialization).mockImplementation(async () => ({ ...plan.status }));
  vi.mocked(api.getKmsInitializationPlan).mockImplementation(async () => structuredClone(plan));
});
it('restores the server step and requires explicit agreement before dispatch', async () => {
  const w = create(); await flushPromises();
  const next = () => w.findAll('button').find((button) => button.text() === '确认并继续')!;
  expect(next().attributes('disabled')).toBeDefined();
  expect(w.text()).toContain('公共用户协议');
  expect(w.text()).not.toContain('租户');
  w.findComponent({ name: 'ElCheckbox' }).vm.$emit('update:modelValue', true);
  await flushPromises();
  vi.mocked(api.confirmKmsInitializationStep).mockResolvedValue({ ...plan, status: { ...plan.status, revision: 2, step: 2 } });
  await next().trigger('click'); await flushPromises();
  expect(api.confirmKmsInitializationStep).toHaveBeenCalledWith(1, expect.objectContaining({ revision: 1, accepted: true, agreementVersion: '2026-10-12' }));
  expect(w.text()).toContain('第 2 / 9 步');
  w.unmount();
});
it('blocks unknown required checks and reloads draft state after a conflict', async () => {
  plan.status.step = 2;
  plan.checks = [{ code: 'redis', step: 2, name: 'Redis', status: 'UNKNOWN', required: true, remedy: '修复连接', checkedAt: Date.now() }];
  const w = create(); await flushPromises();
  expect(w.text()).toContain('修复连接');
  expect(w.findAll('button').find((button) => button.text() === '确认并继续')!.attributes('disabled')).toBeDefined();
  plan.checks[0].status = 'PASS';
  vi.mocked(api.recheckKmsInitialization).mockResolvedValue(structuredClone(plan));
  await w.findAll('button').find((button) => button.text() === '重新检测')!.trigger('click'); await flushPromises();
  vi.mocked(api.confirmKmsInitializationStep).mockRejectedValue(new Error('草稿版本已变化'));
  plan.status.revision = 3;
  plan.status.step = 4;
  await w.findAll('button').find((button) => button.text() === '确认并继续')!.trigger('click'); await flushPromises();
  expect(w.text()).toContain('草稿版本已变化');
  expect(w.text()).toContain('第 4 / 9 步');
  w.unmount();
});
it('runs only self-test in step eight and requires confirmation in step nine', async () => {
  plan.status.step = 8;
  const w = create(); await flushPromises();
  const verified = { ...plan, status: { ...plan.status, revision: 2, step: 9 }, verificationId: 'evidence', expiresAt: Date.now() + 300000 };
  vi.mocked(api.testKmsInitialization).mockResolvedValue(verified);
  await w.findAll('button').find((button) => button.text() === '执行初始化验证')!.trigger('click'); await flushPromises();
  expect(api.testKmsInitialization).toHaveBeenCalledOnce();
  expect(api.completeKmsInitialization).not.toHaveBeenCalled();
  const complete = () => w.findAll('button').find((button) => button.text() === '确认完成初始化')!;
  expect(complete().attributes('disabled')).toBeDefined();
  w.findComponent({ name: 'ElCheckbox' }).vm.$emit('update:modelValue', true); await flushPromises();
  vi.mocked(api.completeKmsInitialization).mockResolvedValue({ ...verified, status: { ...verified.status, locked: true, completedAt: Date.now() } });
  await complete().trigger('click'); await flushPromises();
  expect(api.completeKmsInitialization).toHaveBeenCalledWith(expect.objectContaining({ revision: 2, verificationId: 'evidence', accepted: true }));
  expect(w.text()).toContain('初始化已完成');
  w.unmount();
});
